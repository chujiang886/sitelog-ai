    // 清洗后的文案质量评分（越高越专业）
    function scoreSiteLogText(desc, title, category) {
      if (!desc) return -999;
      const d = String(desc);
      let score = 0;
      // 长度：50~110 字最佳，过短信息量不足，过长啰嗦
      const len = d.length;
      if (len < 20) score -= 40;
      else if (len < 40) score -= 6;
      else if (len <= 120) score += 30;
      else if (len <= 180) score += 18;
      else score += 4;
      // 术语命中（专业度核心）
      let hit = 0;
      AI_STYLE.TERMS.forEach(t => { if (d.includes(t)) hit++; });
      score += Math.min(hit, 6) * 7;
      // 有具体数值/规格更专业（间隙 mm、固化 24h、M10 等）
      // 数字不是可信度证据，不按数值多少奖励文案。
      // 套话扣分
      AI_STYLE.BANNED.forEach(w => { if (d.includes(w)) score -= 14; });
      // 通用模板句直接判废
      AI_STYLE.GENERIC.forEach(w => { if (d.includes(w)) score -= 60; });
      // 与标题重复
      if (title && (d.includes(title) || (title.length > 5 && d.slice(0, title.length) === title))) score -= 20;
      // 与分类名简单复述
      if (category && d.length < 30 && d.includes(category)) score -= 25;
      return score;
    }

    // 本地文案清洗：去拍照腔、去套话修饰、去 emoji/引号、规范标点
    function polishSiteLogText(text, opts) {
      opts = opts || {};
      if (!text) return '';
      let s = String(text).trim();
      // 去 markdown / 代码块残留
      s = s.replace(/```[a-z]*|```/gi, '').trim();
      // 去两端引号与括号包裹
      s = s.replace(/^[\s"'「『【（《<]+/, '').replace(/[\s"'」』】）》>]+$/, '').trim();
      // 去 emoji 与非常规符号
      s = s.replace(/[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}]/gu, '');
      // 去开头序号 / 项目符号
      s = s.replace(/^[-•·*\d]+[.、)．]?\s*/, '');
      const stripHead = (str, re) => {
        let g = 0;
        while (re.test(str) && g++ < 6) str = str.replace(re, '').replace(/^[,，、:：\s]+/, '');
        return str;
      };
      // ① 去拍照腔引导语（"照片中/本图/可以看到/展示了…"）
      const leadRe = /^(照片中|图片中|图中|画面中|本图|这张图片|这张照片|该图|可以看到|可以看出|展示了|显示了|呈现了|体现了|彰显了|值得注意的是|综上所述|总而言之|从照片中|从图片中|从图中|从画面中)/;
      s = stripHead(s, leadRe);
      // ② 去镜头腔（"近景拍摄/特写/俯拍视角：…"）——正式档案不写拍摄手法
      const camRe = /^(近景|远景|特写|俯拍|仰拍|正视|侧拍|平视|室内视角|室外视角|全景|局部)(拍摄|视角|镜头|拍摄了)?(了)?/;
      s = stripHead(s, camRe);
      // ③ 去句中残留的拍照腔
      s = s.replace(/(照片中|图片中|画面中|该图中)(可以看到|可以看出|展示了|显示了)?/g, '');
      s = s.replace(/进行(了)?拍摄/g, '');
      // 去句中拍照腔（"照片中可以看到" 之类残留）
      // 去套话短语（连同后面的"的"结构，尽量不留残句）
      s = s.replace(/(，)?(工艺精湛|做工精细|一丝不苟|质量良好|质量可靠|井然有序|整洁美观|井井有条|美不胜收|展现了专业水平|展现了专业|彰显了专业)(的)?(施工|工艺|水准|态度)?/g, '');
      // 去多余空白
      s = s.replace(/\s{2,}/g, ' ').replace(/\s+([，。；：、])/g, '$1').trim();
      // 去重复标点
      s = s.replace(/[。]{2,}/g, '。').replace(/[，]{2,}/g, '，').replace(/[；]{2,}/g, '；');
      // 清洗后过短（说明原文只是套话，剥完只剩空壳）→ 判为无效，交由兜底处理
      const minLen = opts.minLen || 0;
      if (minLen && s.replace(/[。！？;；，、\s]/g, '').length < minLen) return '';
      // 句末补句号
      if (s && !/[。！？;；]$/.test(s)) s += '。';
      // 超长截断到最后一个句末
      const maxLen = opts.maxLen || 200;
      if (s.length > maxLen) {
        const cut = s.slice(0, maxLen);
        const idx = Math.max(cut.lastIndexOf('。'), cut.lastIndexOf('；'), cut.lastIndexOf('，'));
        s = (idx > maxLen * 0.5 ? cut.slice(0, idx + 1) : cut + '…');
      }
      return s.trim();
    }

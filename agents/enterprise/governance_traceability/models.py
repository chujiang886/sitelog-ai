def _reject_traceability_markers(text: str, *, ctx: str) -> None:
    """追踪层增量语义扫描（红线③/④/⑤），命中即抛红线违例。

    只读校验，**绝不改写文本**（改写等于 AI 悄悄美化事实）。
    """
    if not str(text).strip():
        return
    _reject_markers(
        text, _AUDIT_MUTATION_MARKERS,
        ctx=ctx, rule="治理记录不可变，禁止 AI 自动修改/删除/篡改审计（红线③）",
    )
    _reject_markers(
        text, _CONCLUSION_MARKERS,
        ctx=ctx, rule="治理结论只能由真实人工得出，禁止 AI 自动生成结论（红线④）",
    )
    _reject_markers(
        text, _INCIDENT_CLOSURE_MARKERS,
        ctx=ctx, rule="治理事件只能由真实人工关闭，禁止 AI 自动关闭/结案（红线⑤）",
    )


def _scan(text: str, *, ctx: str) -> None:
    """本层完整语义扫描 = 3.8.21 三组 + 3.8.25 三组 + 3.8.30 三组（共九组）。"""
    if not str(text).strip():
        return
    _reject_all_markers(text, ctx=ctx)
    _reject_traceability_markers(text, ctx=ctx)


def _clean_list(values, *, ctx: str) -> List[str]:
    out: List[str] = []
    for v in values or ():
        s = str(v).strip()
        if not s:
            continue
        _scan(s, ctx=ctx)
        out.append(s)
    return out


def _require_human_review_flag(flag: bool, *, ctx: str) -> None:
    if flag is not True:
        raise EnterpriseRedLineViolationError(
            f"{ctx} 禁止置 requires_human_review=False："
            f"治理事实的采信必须由真实审计责任人完成，AI 不得代替（红线⑥）"
        )


def _guard_activation(ctx: str) -> None:
    if not safety_invariants_ok():
        raise EnterpriseRedLineViolationError(
            f"safety_invariants_ok() 失败：禁止在启用态下构造 {ctx}（红线①）"
        )



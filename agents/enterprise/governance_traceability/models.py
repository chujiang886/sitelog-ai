        self.trace_id = str(self.trace_id).strip()
        self.target_id = str(self.target_id).strip()
        self.org_id = str(self.org_id).strip()
        self.created_at = str(self.created_at).strip()
        self.created_by = str(self.created_by).strip()
        self.note = str(self.note).strip()


@dataclass
class GovernanceTrace:
    """治理全链路追踪（任务1，**全链路唯一，只串事实，不下结论**）。

    ``trace_id`` 在同一组织内全链路唯一（唯一性由
    ``GovernanceTraceabilityService.register_trace`` 强制，重复即拒绝）。

    红线约束：
    - ``trace_id`` / ``source_id`` / ``created_at`` 任一为空即拒绝落库
      （无标识、无来源、无时序的「链路」不是事实，红线⑥：必须可溯源）；
    - 模型中**不存在** conclusion / verdict / root_cause / closed / resolved
      字段——「AI 给结论」「AI 关事件」在类型层面即不可表达（红线④/⑤）；
    - ``requires_human_review`` 恒为 True，禁止置 False（红线⑥）；
    - ``title`` / ``description`` / ``source_facts`` 经**九组语义扫描**，命中
      自动整改 / 自动分配 / 改权限 / 自动审批 / 自动执行 / 生成策略 / 改审计 /
      出结论 / 关事件 任一即拒绝；
    - 模型层**不提供**任何 conclude / close / modify / sign 方法。
    """

    trace_id: str
    source_type: GovernanceTraceSourceType = (
        GovernanceTraceSourceType.HUMAN_REPORTED
    )
    source_id: str = ""
    workflow_id: str = ""
    task_id: str = ""
    created_at: str = ""
    org_id: str = ""
    created_by: str = ""      # 创建者（AI 登记时如实记为 ai，不伪装为人工）
    title: str = ""
    description: str = ""
    source_facts: List[str] = field(default_factory=list)
    references: List[str] = field(default_factory=list)
    requires_human_review: bool = True

    def __post_init__(self) -> None:
        _guard_activation("GovernanceTrace")
        if not isinstance(self.source_type, GovernanceTraceSourceType):
            self.source_type = GovernanceTraceSourceType(self.source_type)

        self.trace_id = str(self.trace_id).strip()
        self.source_id = str(self.source_id).strip()
        self.workflow_id = str(self.workflow_id).strip()
        self.task_id = str(self.task_id).strip()
        self.created_at = str(self.created_at).strip()
        self.org_id = str(self.org_id).strip()
        self.created_by = str(self.created_by).strip()
        self.title = str(self.title).strip()
        self.description = str(self.description).strip()

        ctx = f"GovernanceTrace {self.trace_id!r}"
        if not self.trace_id:
            raise EnterpriseRedLineViolationError(
                "GovernanceTrace 缺少 trace_id：禁止落库无标识的治理链路（红线⑥）"
            )
        if not self.source_id:
            raise EnterpriseRedLineViolationError(
                f"{ctx} 缺少 source_id：禁止落库无来源的治理链路"
                f"（红线⑥：治理事实必须可溯源）"
            )
        if not self.created_at:
            raise EnterpriseRedLineViolationError(
                f"{ctx} 缺少 created_at：无时序的链路无法构成可审计事实（红线⑥）"
            )
        _require_human_review_flag(self.requires_human_review, ctx=ctx)

        _scan(self.title, ctx=f"{ctx}.title")
        _scan(self.description, ctx=f"{ctx}.description")
        self.source_facts = _clean_list(self.source_facts, ctx=f"{ctx}.source_facts")
        self.references = _clean_list(self.references, ctx=f"{ctx}.references")



@dataclass
class AuditViewer:
    """审计查看者载体（任务7：**同时承载「人工证明」与「角色权限」**）。

    追踪层的三道闸门需要两类信息，二者缺一不可：

    - ``actor_kind``：证明操作者是真实人工（交给 ``require_human_actor``，红线⑥）；
    - ``role``：交给 ``AgentPermissionPolicy`` 与 ``IdentityService`` 做审计数据
      隔离（红线⑥）。

    3.8.26 的 ``DashboardUser`` 只有前者，``identity.User`` 只有后者；本载体把两者
    组合起来，**不新增任何权限**，只是把既有身份事实原样转述。``has_permission``
    直接委派给 ``role``，因此 ``IdentityService.check(viewer, perm)`` 可直接使用。
    """

    actor_id: str = ""
    org_id: str = ""
    user: object = None          # identity.User（可选，用于自动填充）
    role: object = None          # identity.Role
    actor_kind: object = AuditActorKind.USER
    display_name: str = ""

    def __post_init__(self) -> None:
        src = self.user
        if src is not None:
            if not str(self.actor_id).strip():
                self.actor_id = str(getattr(src, "user_id", "") or "")
            if not str(self.org_id).strip():
                self.org_id = str(getattr(src, "org_id", "") or "")
            if self.role is None:
                self.role = getattr(src, "role", None)
            if not str(self.display_name).strip():
                self.display_name = str(getattr(src, "name", "") or "")
        self.actor_id = str(self.actor_id).strip()
        self.org_id = str(self.org_id).strip()

    @classmethod
    def from_user(cls, user: object, *, actor_kind: object = AuditActorKind.USER) -> "AuditViewer":
        """由 ``identity.User`` 构造查看者（**不改变任何权限事实**）。"""
        return cls(user=user, actor_kind=actor_kind)

    def has_permission(self, perm: object) -> bool:
        """委派给角色的权限判定（无角色 → 默认拒绝）。"""
        role = self.role
        if role is None:
            return False
        checker = getattr(role, "has", None)
        if checker is None:
            return False
        try:
            return bool(checker(perm))
        except Exception:
            return False

    def is_user(self) -> bool:
        return str(self.actor_kind).lower().endswith("user")



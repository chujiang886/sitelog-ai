"""Phase 3.8.30 企业智能体治理全链路追踪与统一审计智能层 —— 模型层。

定位（**复用而非重建**）：
- 3.8.21 ``agent_governance_workflow`` 回答「这条治理发现由谁负责、谁确认闭环」；
- 3.8.25 ``governance_workflow`` 回答「一条治理线索如何从发现走到归档」；
- 3.8.26 ``governance_dashboard`` 回答「人工在一个界面上能看到什么、确认什么」；
- **3.8.30 本层**回答「**这件事的全链路事实是什么、来自哪里、按什么顺序发生**」。

本层是**纯只读的事实串联层**：只把既有事实（事件 / 工作流 / 任务 / 审计 / 知识）
用 ``GovernanceTrace`` 串起来，并以时间线 / 重放 / 来源链三种只读视图呈现。它
**不产生任何新的治理判断**。

模型清单：
- 任务1：``GovernanceTraceSourceType`` / ``GovernanceTrace``（全链路唯一 trace）。
- 任务2：``GovernanceTraceLinkKind`` / ``GovernanceTraceLink``（**只建立关联**）。
- 任务3：``GovernanceAuditTimelineEntry`` / ``GovernanceAuditTimeline``（只读时间线）。
- 任务4：``GovernanceReplayStep`` / ``GovernanceReplayView``（**重建事实，禁止重新执行**）。
- 任务5：``SourceTrace`` / ``GovernanceTraceReport``（完整来源链）。

红线（fail-closed，三重拦截之「类型级 + 语义级」；结构级见 ``forbidden.py``）：
① 所有模型构造断言 ``safety_invariants_ok()``（engineering_enabled 必须 False）。
② 不承载 ``engineering_approved`` 语义；无任何 approve / sign 字段。
③ 禁 AI 自动修改治理记录：视图模型一律 ``frozen=True``（不可变），且经
   ``_AUDIT_MUTATION_MARKERS`` 语义扫描。
④ 禁 AI 自动生成治理结论：模型中**刻意不存在** ``conclusion`` / ``verdict`` /
   ``root_cause`` 字段；``GovernanceTraceReport.conclusion_included`` 恒为 False。
⑤ 禁 AI 自动关闭事件：模型中**刻意不存在** ``closed`` / ``resolved`` 字段；
   ``GovernanceReplayStep.re_executed`` 恒为 False（重放≠重新执行）。
⑥ 禁 AI 代替审计责任人：``requires_human_review`` 恒为 True，禁止置 False。
"""

